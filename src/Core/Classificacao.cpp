#include "Classificacao.h"

//----------------------------------------------------------------------------------------------

TAresta::TAresta(
  const TVetor3D& inicio,
  const TVetor3D& fim
) :
  inicio(inicio),
  fim(fim)
{
}

//----------------------------------------------------------------------------------------------

const TVetor3D& TAresta::Inicio() const
{
  return inicio;
}

//----------------------------------------------------------------------------------------------

const TVetor3D& TAresta::Fim() const
{
  return fim;
}

//----------------------------------------------------------------------------------------------

TVetor3D TAresta::Direcao() const
{
  return fim - inicio;
}

//----------------------------------------------------------------------------------------------

TVetor3D TAresta::Ponto(
  double t
) const
{
  return inicio + t * Direcao();
}

